// The yakhchal town as one three.js scene: sky (stars at night), the desert town with its ice-house dome, square, houses,
// palms, the shade wall and the ice pool, the sled of ice; the dome's inside (the pit) and a night kitchen with a
// freezer far away.
// update(id, f, camera) poses everything for shot `id` at frame f (pure function of id + f).
