"""words.json -> named word onsets W (seconds) for story.ts (words.ts) and the sound (w.json). Sequential keyword match."""
import json, re, sys
w = json.load(open(sys.argv[1]))
toks = [(re.sub(r"[^a-z0-9]", "", x["w"].lower()), x["s"], x["e"]) for x in w]
KEYS = [("biggest", "biggest"), ("never", "never"), ("sound", "sound"), ("because", "because"), ("save", "save"),
  ("moscow", "moscow"), ("empress", "empress"), ("kremlin", "kremlin"), ("not", "not"), ("biggest2", "biggest"),
  ("two", "two|200|twohundred"), ("bronze", "bronze"), ("taller", "taller"), ("giraffe", "giraffe"), ("heavy", "heavy"), ("pit", "pit"),
  ("ten", "ten|10"), ("deep", "deep"), ("may", "may"), ("fire", "fire"), ("scaffolding", "scaffolding"), ("flames", "flames"),
  ("hot", "hot"), ("really", "really"), ("guards", "guards"), ("sensible", "sensible"), ("grab", "grab"), ("pour", "pour"),
  ("water", "water"), ("crack", "crack"), ("another", "another"), ("eleven", "eleven|11"), ("chunk", "chunk"), ("off", "off"),
  ("luckily", "luckily"), ("fall", "fall"), ("unluckily", "unluckily"), ("ninety", "ninety|99|ninetynine"), ("years", "years"),
  ("yousee", "you"), ("grows", "grows"), ("shrinks", "shrinks"), ("shrank", "shrank"), ("inside", "inside"), ("ice", "ice"),
  ("dish", "dish"), ("something", "something"), ("give", "give"), ("eighteen", "in|eighteen|1836"), ("lifted", "lifted"), ("stone", "stone"),
  ("broken", "broken"), ("heres", "here|heres"), ("third", "third"), ("first", "first"), ("second", "second"), ("survived", "survived"),
  ("water2", "water"), ("got", "got")]
i, W = 0, {}
for k, pat in KEYS:
    j = i
    while j < len(toks) and not re.fullmatch(pat, toks[j][0]): j += 1
    if j == len(toks): print("MISSING", k, file=sys.stderr); continue
    W[k] = round(toks[j][1], 3); i = j + 1
W["end"] = round(toks[-1][2], 3)
json.dump(W, open(sys.argv[2], "w"), indent=1)
open(sys.argv[3], "w").write("// generated by tools/make_words.py from voice/words.json (word onsets, s)\nexport const W = " + json.dumps(W, indent=1) + " as const;\n")
print(W)
