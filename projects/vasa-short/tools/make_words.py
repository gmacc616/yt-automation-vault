"""words.json -> named word onsets W (seconds) for story.ts (words.ts) and the sound (w.json). Sequential keyword match."""
import json, re, sys
w = json.load(open(sys.argv[1]))
toks = [(re.sub(r"[^a-z0-9]", "", x["w"].lower()), x["s"], x["e"]) for x in w]
KEYS = [("most", "most"), ("harbour", "harbour|harbor"), ("stockholm", "stockholm"), ("king", "king"), ("terrify", "terrify"),
  ("so", "so"), ("vasa", "vasa|vaasa|vasah|vasta|vassa"), ("sixty", "sixty|64|sixtyfour"), ("golden", "golden"), ("problem", "problem"), ("before", "before"),
  ("admiral", "admiral"), ("thirty", "thirty|30"), ("once", "once"), ("twice", "twice"), ("three", "three|3"), ("rolled", "rolled"),
  ("stop", "stop"), ("fix", "fix"), ("nope", "nope"), ("nobody", "nobody"), ("tellking", "king"), ("august", "august"), ("crowds", "crowds"),
  ("breeze", "breeze"), ("tipped", "tipped"), ("cameback", "came"), ("second", "second"), ("water", "water"), ("gunports", "gunports|gun|ports"),
  ("twenty", "twenty|20"), ("thirteen", "thirteen|1300|thirteenhundred"), ("gone", "gone"), ("lucky", "luckily"), ("crew", "crew"),
  ("unlucky", "unluckily"), ("watched", "watched"), ("yousee", "you"), ("bus", "bus"), ("low", "low"), ("bump", "bump"), ("over", "over"),
  ("turn", "turn"), ("flying", "flying"), ("vasa2", "vasa|vaasa|vasah|vasta|vassa"), ("high", "high"), ("inquiry", "inquiry"), ("blame", "blame"),
  ("nobody2", "nobody"), ("but", "but"), ("impress", "impress"), ("did", "did"), ("pulled", "pulled"), ("nineteen", "nineteen|1961|in"),
  ("million", "million|29|twentynine"), ("visited", "visited"), ("still", "still"), ("stockholm2", "stockholm")]
i, W = 0, {}
for k, pat in KEYS:
    j = i
    while j < len(toks) and not re.fullmatch(pat, toks[j][0]): j += 1
    if j == len(toks): print("MISSING", k, file=sys.stderr); continue
    W[k] = round(toks[j][1], 3); i = j + 1
W.update({"stockholm": 3.97, "august": 27.7, "crowds": 28.55})  # hand-fixed at chunk starts (energy onsets)
W["end"] = round(toks[-1][2], 3)
json.dump(W, open(sys.argv[2], "w"), indent=1)
open(sys.argv[3], "w").write("// generated by tools/make_words.py from voice/words.json (word onsets, s)\nexport const W = " + json.dumps(W, indent=1) + " as const;\n")
print(W)
